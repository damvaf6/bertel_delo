-- Подходы к оценке, которые применяет исполнитель (2.33, прогон «как настоящий эксперт» по отчёту «221»): черновик от ИИ
-- пишется только с разделами применённых подходов и сплошной нумерацией, таблица «подход — стоимость — вес» — только с ними,
-- аналоги не требуются, если сравнительный подход не применяется. null — исполнитель ещё не выбрал (все разделы, как раньше).
alter table orders add column approaches text[]
  check (approaches is null or (cardinality(approaches) between 1 and 3 and approaches <@ array['comparative', 'cost', 'income']));
