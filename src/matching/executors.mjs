import { HttpError } from '../http/core.mjs';

export const TAX_STATUSES = Object.freeze({
  self_employed: {
    name: 'Самозанятый',
    // Правило для самозанятых: чек на каждую выплату (задача штаба 3f417197-6878-813c-92ad-f96b48358ad4).
    rules: [
      'На каждую выплату от платформы формируете чек в приложении «Мой налог» в день получения денег.',
      'Покупатель в чеке — платформа (юридическое лицо), назначение — услуга по заявке с её номером.',
      'Ссылку на чек прикладываете к выплате в разделе «Деньги». Без чека выплату нельзя учесть как расход платформы.',
      'Если статус самозанятого прекращён — сразу сообщите платформе: новые дела не предлагаются до смены статуса.',
    ],
  },
  ip: { name: 'Индивидуальный предприниматель', rules: ['Выплаты — на расчётный счёт ИП; закрывающие документы — акт и отчёт агента в деле.'] },
  company: { name: 'ООО или бюро переводов', rules: ['Выплаты — на расчётный счёт организации; закрывающие документы — акт и отчёт агента в деле.'] },
});

export function taxStatusFrom(value) {
  if (value === null) return null;
  if (!Object.hasOwn(TAX_STATUSES, value)) throw new HttpError(400, 'bad_input', 'Поле «Статус»: самозанятый, ИП или ООО/бюро');
  return value;
}

// Ссылка на чек «Мой налог»: только с сайта ФНС (lknpd.nalog.ru), https.
export function receiptUrlFrom(value) {
  const raw = String(value ?? '').trim();
  if (raw.length === 0 || raw.length > 300) return null;
  let u;
  try { u = new URL(raw); } catch { return null; }
  if (u.protocol !== 'https:' || u.hostname !== 'lknpd.nalog.ru' || u.username || u.password) return null;
  return u.toString();
}
