// Вопросы суда к эксперту (задача 2.444): суд вызвал эксперта дать пояснения к отчёту (2.441) и в определении или повестке
// перечислил вопросы. Модель ИИ делит текст на отдельные вопросы (подсказка — courtMessages), ответ чистится как у
// замечаний (cleanItems), а если модель вернула не то — вопросы по нумерации текста (splitRemarks). Вопросы только
// предлагаются: эксперт правит, удаляет, добавляет свои и сам пишет пояснение к каждому и где в отчёте.
import { SOURCE_MAX, splitRemarks } from './remarks.mjs';

export { ITEM_MAX, ITEMS_MAX, PLACE_MAX, SOURCE_MAX, cleanItems, splitRemarks } from './remarks.mjs';
export const ANSWER_MAX = 3000;

// Что уходит модели: текст, вписанный экспертом, и текст файла повестки или определения. Модель только выбирает вопросы
// к эксперту — слово в слово, не отвечает на них и не придумывает своих.
export function courtMessages({ text, file }) {
  return [
    { role: 'system', content: 'Ты помогаешь эксперту-оценщику. Суд вызвал эксперта дать пояснения к отчёту об оценке. Найди в '
      + 'тексте вопросы суда или сторон к эксперту и раздели их на отдельные пункты: один пункт — один вопрос. Пиши слово в '
      + 'слово, как в тексте, без номеров. Не отвечай на вопросы и не добавляй своих. Шапку, реквизиты, состав суда, '
      + 'резолютивную часть без вопросов и подписи не бери. Ответ — только JSON: {"items": ["…", "…"]}.' },
    { role: 'user', content: `ВОПРОСЫ (вписал эксперт):\n${text || '—'}\n\nФАЙЛ ОПРЕДЕЛЕНИЯ ИЛИ ПОВЕСТКИ:\n${file ? file.slice(0, SOURCE_MAX) : '—'}` },
  ];
}

// Поддельная модель: вопросы по нумерации — сначала из вписанного экспертом, нет — из файла (после «вопрос…:», если есть).
export function fakeCourtItems(prompt) {
  const [head, file = ''] = String(prompt).split('ФАЙЛ ОПРЕДЕЛЕНИЯ ИЛИ ПОВЕСТКИ:\n');
  const said = head.replace(/^ВОПРОСЫ \(вписал эксперт\):\n/, '').trim();
  const fromSaid = said && said !== '—' ? splitRemarks(said) : [];
  const tail = file.trim() === '—' ? '' : file.replace(/^[\s\S]*?вопрос[а-я]*[^\n:]*:\s*\n/iu, '');
  return JSON.stringify({ items: fromSaid.length ? fromSaid : splitRemarks(tail) });
}
