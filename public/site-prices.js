// 4000 → «от 4 000 ₽» (неразрывные пробелы — «₽» не отрывается от суммы).
export function priceText(rub) {
  return `от ${String(rub).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₽`;
}

