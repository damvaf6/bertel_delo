// Какие роли у вошедшего: заказчиком может быть каждый; остальные — по профилю.
export function myRoles() {
  const me = state.me;
  const roles = [];
  if (['dispatcher', 'admin'].includes(me.user.platform_role)) roles.push('dispatcher');
  if (me.orgs.some((o) => o.role === 'head')) roles.push('head');
  if (state.specialist) roles.push('expert');
  roles.push('customer');
  return roles;
}

// «С чего начать» — первая незакрытая подсказка по ролям (по одной за раз).
export function showFirstHint() {
  const box = $('hint-box');
  const role = myRoles().find((r) => !(state.me.hints_seen || []).includes(r));
  box.classList.toggle('hidden', !role);
  if (!role) return;
  const r = ROLES[role];
  box.dataset.role = role;
  $('hint-title').textContent = `С чего начать: ${r.name.toLowerCase()}`;
  $('hint-steps').replaceChildren(...r.first.map((t) => el('li', { text: t })));
}

async function closeHint() {
  const role = $('hint-box').dataset.role;
  $('hint-box').classList.add('hidden');
  try {
    state.me.hints_seen = (await api('POST', '/api/me/hints', { hint: role })).hints_seen;
  } catch {
    state.me.hints_seen = [...(state.me.hints_seen || []), role];
  }
  showFirstHint();
}
$('hint-ok').addEventListener('click', closeHint);

// «Как работать»: сначала свои роли (раскрыты), потом остальные (свёрнуты).
export function showHelp() {
  const mine = myRoles();
  const order = [...mine, ...Object.keys(ROLES).filter((r) => !mine.includes(r))];
  $('help-roles').replaceChildren(...order.map((id) => {
    const r = ROLES[id];
    const d = el('details', { class: 'card help-role', 'data-role': id },
      el('summary', {}, el('h2', { text: r.name })),
      el('h3', { text: 'С чего начать' }),
      el('ol', { class: 'howto' }, ...r.first.map((t) => el('li', { text: t }))),
      ...r.guide.flatMap(([h, items]) => [el('h3', { text: h }), el('ul', { class: 'plain' }, ...items.map((t) => el('li', { text: t })))]));
    if (mine.includes(id)) d.open = true;
    return d;
  }));
  show('help-view', 'help');
}
