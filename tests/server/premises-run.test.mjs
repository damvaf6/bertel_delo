// Прогон 2.528 (пачка «Нежилое помещение и доходный подход»): сверка отчёта «аналогов не меньше трёх» (analog_list) не
// считает аналоги аренды (2.523) — номера из таблицы «Аналоги аренды …» и «Аналог N … (аренда)» в приложении. Раньше два
// аналога продажи и один аренды проходили как «три аналога».
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { runAutoChecks } from '../../src/ai/report-checks.mjs';

const doc = (text) => ({ name: 'Отчёт.docx', kind: 'docx', pages: [text] });
const list = (text) => runAutoChecks(['analog_list'], [doc(text)]).analog_list.map((x) => x.text);
const SALES = (n) => ['Сравнительный подход', '| № | Источник | Цена, руб. | Площадь, кв. м | Регион |',
  ...Array.from({ length: n }, (_, i) => `| ${i + 1} | cian.ru | ${30 + i} 000 000 | 100 | Москва |`)];
const RENT = (from) => ['Аналоги аренды (для доходного подхода; в сравнительный подход не идут):',
  '| № | Источник | Плата в месяц, руб. | Площадь, кв. м | Ставка, руб. за кв. м в месяц | Регион |',
  `| ${from} | cian.ru | 150 000 | 100 | 1 500 | Москва |`, `| ${from + 1} | avito.ru | 200 000 | 100 | 2 000 | Москва |`,
  `Средняя ставка аренды аналогов ${from}, ${from + 1} — 1 750 руб. за кв. м в месяц (21 000 руб. за кв. м в год).`];
const APPENDIX = (sales, rents) => ['Приложение. Скриншоты объявлений-аналогов',
  ...Array.from({ length: sales }, (_, i) => `Аналог ${i + 1} — cian.ru\nСсылка: https://www.cian.ru/sale/commercial/${i + 1}/`),
  ...Array.from({ length: rents }, (_, i) => `Аналог ${sales + i + 1} — cian.ru (аренда)\nСсылка: https://www.cian.ru/rent/commercial/${sales + i + 1}/`)];

test('два аналога продажи и два аренды — находка «два аналога продажи»; три продажи — молчит', () => {
  const two = [...SALES(2), ...RENT(3), ...APPENDIX(2, 2)].join('\n');
  assert.deepEqual(list(two), ['В сравнительном подходе два аналога продажи — нужно не меньше трёх (аналоги аренды не в счёт)']);
  const three = [...SALES(3), ...RENT(4), ...APPENDIX(3, 2)].join('\n');
  assert.deepEqual(list(three), []);
  // Без аналогов аренды — как раньше.
  assert.deepEqual(list([...SALES(2), ...APPENDIX(2, 0)].join('\n')), ['В сравнительном подходе два аналога — нужно не меньше трёх']);
  assert.deepEqual(list([...SALES(3), ...APPENDIX(3, 0)].join('\n')), []);
  // Отказ от сравнительного подхода — молчит, как раньше.
  assert.deepEqual(list(['Сравнительный подход не применялся: аналог №1 найден один.', ...RENT(2)].join('\n')), []);
});

test('квартира: «аналог» рядом со словом «аренда» в описании не делает его арендой без таблицы аренды', () => {
  const text = ['Сравнительный подход', 'Аналог 1 — квартира, продажа, ранее сдавалась в аренду', 'Аналог 2 — квартира', 'Аналог 3 — квартира'].join('\n');
  assert.deepEqual(list(text), []);
});
