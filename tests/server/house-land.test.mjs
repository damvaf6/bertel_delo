// Задача 2.532 (жилой дом с участком): ИИ-проверка house_land — участок под домом в собственности: стоимость участка в отчёте
// есть, дом + участок = итог, пропусков «[заполнить]» нет; кадастровый номер и площадь участка — как в выписке ЕГРН на участок.
// Без сервера — только правило и описание модуля.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRegistry } from '../../src/modules/index.mjs';
import { runAutoChecks, AUTO_CHECKS } from '../../src/ai/report-checks.mjs';
import { houseTable } from '../../src/orders/house.mjs';

const HOUSE = { object_type: 'house', area: 120, house_land: 'own', land_cadastral: '50:20:0010203:45', land_area: 15 };
const doc = (lines) => ({ name: 'Отчёт.pdf', kind: 'pdf', pages: [['ОТЧЁТ ОБ ОЦЕНКЕ № 41', 'Объект оценки: жилой дом с земельным участком', ...lines].join('\n')] });
const run = (lines, fields = HOUSE, egrn = []) => runAutoChecks(['house_land'], [doc(lines)], { service: 'realty', fields, egrn }).house_land;
const TABLE = [
  '| Стоимость дома и участка | Значение |',
  '| Жилой дом, руб. | 8 000 000 |',
  '| Земельный участок под домом, руб. | 2 000 000 |',
  '| Итого: дом и участок (единый объект, ст. 35 ЗК РФ), руб. | 10 000 000 |',
  '| Доля участка в итоговой стоимости, % | 20 |',
];
const LAND_EGRN = { id: 'e1', name: 'Выписка на участок.pdf', land: true, pages: [[
  'Выписка из Единого государственного реестра недвижимости об объекте недвижимости',
  'Вид объекта недвижимости: Земельный участок',
  'Кадастровый номер: 50:20:0010203:45',
  'Площадь: 1500 +/- 14 кв. м',
].join('\n')] };

test('таблица сходится — молчим; итог не равен дому + участку — находка с верной суммой', () => {
  assert.ok(AUTO_CHECKS.house_land, 'правило описано');
  assert.deepEqual(run(TABLE), []);
  const bad = TABLE.map((l) => l.replace('10 000 000', '10 500 000'));
  const res = run(bad);
  assert.equal(res.length, 1, JSON.stringify(res));
  assert.equal(res[0].text, 'Итог «дом и участок» 10 500 000 руб. не равен сумме: дом 8 000 000 + участок 2 000 000 = 10 000 000 руб. — пересчитайте итог или исправьте стоимость дома или участка');
  assert.deepEqual(res[0].fix, { bad: '10 500 000', right: '10 000 000', from: 'по расчёту дом 8 000 000 + участок 2 000 000' });
  // Текстом, без таблицы — так же.
  assert.deepEqual(run(['Стоимость жилого дома: 8 000 000 руб.', 'Стоимость земельного участка: 2 000 000 руб.', 'Итоговая рыночная стоимость жилого дома с земельным участком: 10 000 000 руб.']), []);
  assert.equal(run(['Стоимость жилого дома: 8 000 000 руб.', 'Стоимость земельного участка: 2 000 000 руб.', 'Итоговая рыночная стоимость жилого дома с земельным участком: 9 000 000 руб.']).length, 1);
  // Ячейки Word — своими строками.
  assert.deepEqual(run(['Стоимость дома и участка', 'Значение', 'Жилой дом, руб.', '8 000 000', 'Земельный участок под домом, руб.', '2 000 000', 'Итого: дом и участок (единый объект, ст. 35 ЗК РФ), руб.', '10 000 000']), []);
});

test('стоимости участка нет или пропуски «[заполнить]» — находка; участок не в собственности или не дом — молчим', () => {
  let res = run(['Итоговая рыночная стоимость жилого дома: 8 000 000 руб.']);
  assert.equal(res.length, 1, JSON.stringify(res));
  assert.match(res[0].text, /^Участок под домом по заявке в собственности, а стоимости участка в отчёте не найдено/);
  // Таблица из черновика как есть — пропуски.
  res = run(houseTable('realty', HOUSE));
  assert.equal(res.length, 1, JSON.stringify(res));
  assert.equal(res[0].text, 'В таблице «Стоимость дома и участка» остались пропуски «[заполнить]» (3) — впишите стоимость дома, участка и итог');
  // Описание участка с площадью — не стоимость.
  assert.equal(run(['Земельный участок под домом площадью 1500 кв. м, категория земель — земли населённых пунктов', 'Итоговая рыночная стоимость жилого дома: 8 000 000 руб.']).length, 1);
  for (const house_land of ['lease', 'none', undefined]) assert.deepEqual(run(['Итоговая стоимость: 8 000 000 руб.'], { ...HOUSE, house_land }), []);
  assert.deepEqual(run(['Итоговая стоимость: 8 000 000 руб.'], { ...HOUSE, object_type: 'flat' }), []);
  assert.deepEqual(runAutoChecks(['house_land'], [doc(['Итоговая стоимость: 8 000 000 руб.'])], { service: 'vehicle', fields: HOUSE }).house_land, []);
});

test('кадастровый номер и площадь участка — как в выписке ЕГРН на участок', () => {
  const ok = [...TABLE, 'Жилой дом с кадастровым номером 50:20:0010203:301 расположен на земельном участке с кадастровым номером 50:20:0010203:45 площадью 15 соток.', 'Общая площадь дома 120 кв. м'];
  assert.deepEqual(run(ok, HOUSE, [LAND_EGRN]), []);
  // Таблица 2.531 из черновика с номером и площадью по заявке.
  assert.deepEqual(run(['| Земельный участок под домом (кадастровый номер 50:20:0010203:45, 15 сот. — по заявке, сверьте с выпиской ЕГРН на участок), руб. | 2 000 000 |', ...TABLE.slice(1)], HOUSE, [LAND_EGRN]), []);
  let res = run([...TABLE, 'Земельный участок: кадастровый номер 50:20:0010203:46, площадь 1500 кв. м'], HOUSE, [LAND_EGRN]);
  assert.equal(res.length, 1, JSON.stringify(res));
  assert.equal(res[0].text, 'Кадастровый номер участка под домом в отчёте 50:20:0010203:46, а в выписке ЕГРН на участок — 50:20:0010203:45: проверьте, не номер ли это другого участка');
  assert.deepEqual(res[0].fix, { bad: '50:20:0010203:46', right: '50:20:0010203:45', from: 'по выписке ЕГРН на участок «Выписка на участок.pdf»' });
  res = run([...TABLE, 'Земельный участок: кадастровый номер 50:20:0010203:45, площадь 12 соток'], HOUSE, [LAND_EGRN]);
  assert.equal(res.length, 1, JSON.stringify(res));
  assert.equal(res[0].text, 'Площадь участка под домом в отчёте 12 соток (1 200 кв. м), а в выписке ЕГРН на участок — 1 500 кв. м (15 сот.)');
  assert.equal(res[0].fix.right, '15');
  res = run([...TABLE, 'Площадь земельного участка: 1200 кв. м'], HOUSE, [LAND_EGRN]);
  assert.match(res.find((f) => /кадастровый номер участка/.test(f.text)).text, /не указан кадастровый номер участка под домом — по выписке ЕГРН на участок 50:20:0010203:45/);
  assert.equal(res.find((f) => /Площадь участка/.test(f.text)).fix.right, '1 500');
  // Без выписки на участок — номер и площадь не сверяем.
  assert.deepEqual(run([...TABLE, 'Земельный участок: кадастровый номер 50:20:0010203:46, площадь 12 соток']), []);
});

test('пункт проверки — только у жилого дома', () => {
  const reg = createRegistry();
  assert.ok(reg.checks('expertise', 'realty', HOUSE).some((c) => (c.auto ?? []).includes('house_land')));
  assert.equal(reg.checks('expertise', 'realty', { object_type: 'flat' }).some((c) => (c.auto ?? []).includes('house_land')), false);
});
