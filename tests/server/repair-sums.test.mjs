// 2.474: ИИ-проверка заключения по ДТП — сумма с износом не больше суммы без износа и одна в расчёте и выводах; УТС
// легкового автомобиля старше 5 лет или с пробегом больше 100 000 км не считают (рекомендации РФЦСЭ 2018); об УТС сказано;
// в выводах суммы прописью. Сумма цифрами и прописью — `sum_words` (пункт «Расчёт»). Находки — в пункте «Стоимость ремонта».
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { runAutoChecks } from '../../src/ai/report-checks.mjs';
import { DEFAULT_MODULES } from '../../src/modules/index.mjs';

const REPORT = [
  'ЗАКЛЮЧЕНИЕ ЭКСПЕРТА № 12',
  '7. Расчёт стоимости восстановительного ремонта',
  'Стоимость запасных частей с учётом износа 95 000 руб.',
  'Стоимость ремонтных работ без учёта износа 300 000 руб.',
  'Стоимость восстановительного ремонта без учёта износа: 245 300,00 руб.',
  'Стоимость восстановительного ремонта с учётом износа: 180 150,00 руб.',
  '8. Утрата товарной стоимости',
  'Утрата товарной стоимости составляет 21 400 руб.',
  '9. Выводы',
  'Стоимость восстановительного ремонта автомобиля без учёта износа на дату ДТП составляет 245 300 (Двести сорок пять тысяч триста) рублей, с учётом износа — 180 150 (Сто восемьдесят тысяч сто пятьдесят) рублей.',
  'Утрата товарной стоимости составляет 21 400 руб. (Двадцать одна тысяча четыреста рублей).',
  '10. Приложения',
].join('\n');
const FIELDS = { vehicle_type: 'car', year: 2022, mileage: 40000, accident_date: '14.09.2026' };
const run = (text, fields, rules = ['repair_sums']) => runAutoChecks(rules, [{ name: 'Заключение.docx', pages: [text] }],
  { service: 'car_damage', fields: { ...FIELDS, ...fields } });

test('всё сходится — без находок; правило стоит в пункте «Стоимость ремонта»', () => {
  assert.deepEqual(run(REPORT).repair_sums, []);
  const item = DEFAULT_MODULES.find((m) => m.id === 'expertise').checks.find((c) => c.id === 'cd_cost');
  assert.ok(item.auto.includes('repair_sums'));
  assert.deepEqual(runAutoChecks(['repair_sums'], [{ name: 'a', pages: [REPORT] }], { service: 'vehicle', fields: {} }).repair_sums, []);
});

test('с износом больше, чем без износа; итоги в расчёте и выводах разные', () => {
  const swapped = REPORT.replace('без учёта износа: 245 300,00', 'без учёта износа: 170 000,00');
  const f = run(swapped).repair_sums.map((x) => x.text);
  assert.equal(f[0], 'Стоимость ремонта с учётом износа (180 150 руб.) больше, чем без учёта износа (170 000 руб.): износ только уменьшает сумму — проверьте расчёт и не перепутаны ли суммы местами');
  assert.equal(f[1], 'Стоимость ремонта без учёта износа в отчёте разная: 170 000 руб. (стр. 1) и 245 300 руб. (стр. 1) — итог в расчёте и выводах должен быть один');
  assert.equal(f.length, 2);
  // Запчасти и работы с износом и без — не итог ремонта.
  assert.deepEqual(run(REPORT.replace('с учётом износа 95 000', 'с учётом износа 395 000')).repair_sums, []);
});

test('УТС у автомобиля старше 5 лет или с пробегом больше 100 000 км — находка; «не рассчитывается» — без находки', () => {
  const old = run(REPORT, { year: 2019 }).repair_sums;
  assert.equal(old.length, 1);
  assert.equal(old[0].text, 'Утрата товарной стоимости посчитана (21 400 руб.), а автомобиль 2019 года выпуска — на дату ДТП ему больше 5 лет: по Методическим рекомендациям ФБУ РФЦСЭ (2018) УТС легкового автомобиля старше 5 лет или с пробегом больше 100 000 км не рассчитывается — уберите УТС или объясните в разделе, почему считаете');
  assert.equal(old[0].quote, 'Утрата товарной стоимости составляет 21 400 руб.');
  assert.match(run(REPORT, { mileage: 120000 }).repair_sums[0].text, /пробег по заявке 120 000 км — больше 100 000 км/);
  // Ровно 5 лет по году выпуска — может быть и меньше 5: молчим. Грузовик — не по этим порогам.
  assert.deepEqual(run(REPORT, { year: 2021 }).repair_sums, []);
  assert.deepEqual(run(REPORT, { year: 2015, vehicle_type: 'truck' }).repair_sums, []);
  const noUts = REPORT.replace('Утрата товарной стоимости составляет 21 400 руб.\n9.', 'УТС не рассчитывается: срок эксплуатации более 5 лет.\n9.')
    .replace('Утрата товарной стоимости составляет 21 400 руб. (Двадцать одна тысяча четыреста рублей).\n', '');
  assert.deepEqual(run(noUts, { year: 2019 }).repair_sums, []);
});

test('об УТС ничего нет — находка (с причиной, если автомобиль старый)', () => {
  const none = REPORT.replace(/8\. Утрата[^\n]*\n[^\n]*\n/u, '').replace(/Утрата товарной стоимости составляет 21 400 руб\. \([^)]*\)\.\n/u, '');
  const f = run(none).repair_sums;
  assert.equal(f.length, 1);
  assert.match(f[0].text, /^Об утрате товарной стоимости в отчёте ничего нет — посчитайте УТС или напишите одной строкой/);
  assert.match(run(none, { year: 2018 }).repair_sums[0].text, /^Об утрате товарной стоимости в отчёте ничего нет: автомобиль 2018 года выпуска/);
});

test('в выводах сумма без прописи — находка; пропись не та — находка `sum_words`', () => {
  const bare = REPORT.replace(' (Сто восемьдесят тысяч сто пятьдесят) рублей', ' руб.');
  const f = run(bare).repair_sums;
  assert.equal(f.length, 1);
  assert.equal(f[0].text, 'В выводах стоимость ремонта с учётом износа (180 150 руб.) — только цифрами: напишите сумму и прописью, например «(сто восемьдесят тысяч сто пятьдесят рублей)»');
  const wrong = run(REPORT.replace('(Двести сорок пять тысяч триста)', '(Двести сорок пять тысяч)'), {}, ['sum_words']).sum_words;
  assert.equal(wrong.length, 1);
  assert.match(wrong[0].text, /^Сумма цифрами 245 300 не совпадает с суммой прописью \(245 000\)/);
});
